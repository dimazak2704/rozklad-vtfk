import { describe, expect, it } from 'vitest';
import { momentText } from './format';

describe('момент відповіді викладача', () => {
  it('сьогодні — лише час', () => {
    // 01:15 за Києвом 20.11 (UTC+2)
    expect(momentText('2026-11-19T23:15:00Z', '2026-11-20')).toBe('о 01:15');
  });

  it('іншого дня — дата й час: «14.11 о 01:15»', () => {
    expect(momentText('2026-11-13T23:15:00Z', '2026-11-20')).toBe('14.11 о 01:15');
    // межа доби — за Києвом, не за UTC
    expect(momentText('2026-11-19T22:30:00Z', '2026-11-19')).toBe('20.11 о 00:30');
  });

  it('іншого року — з роком', () => {
    expect(momentText('2025-12-30T08:00:00Z', '2026-01-02')).toBe('30.12.2025 о 10:00');
  });
});
